"""Export the moth to C for the Gigatron (glcc).

Every array is at most 96 bytes so the glcc linker can scatter it into the
96-byte holes of the 32K Gigatron video memory.

Matrix format: a list of chunks; chunk = [nrows, row, row, ...];
row = [n, b ...] with b = 2*i (+1 weight) or 0x80 | 2*i (-1 weight): indices are
pre-doubled because activations are int16.

Usage: python export_c.py moth.pt ../gigatron/src/weights.c
"""
import sys

import torch

from qmodel import CTX, EXP, RCP, QMoth

XROW = 71            # screen row used as the activation page (page 0x4f, see row.s)
CHUNK = int(__import__('os').environ.get('CHUNK', 96))
BRAIN_ROWS = int(__import__("os").environ.get("BRAIN_ROWS", 72))      # screen rows 0..BRAIN_ROWS-1: the "brain" (model data); below: title, chat and the ROM Loader


def rows_of(W):
    out = []
    for row in W.tolist():
        b = [2 * i | (0x80 if w < 0 else 0) for i, w in enumerate(row) if w]
        out.append([len(b)] + b)
    return out


def chunks_of(rows):
    chunks, cur = [], []
    for r in rows:
        if 1 + sum(map(len, cur)) + len(r) > CHUNK:
            chunks.append(cur); cur = []
        cur.append(r)
    chunks.append(cur)
    return [[len(c)] + [x for r in c for x in r] for c in chunks]


def carr(name, data, ctype="unsigned char"):
    body = ",".join(str(x) for x in data)
    return f"{ctype} {name}[{len(data)}] = {{{body}}};\n"


def main(ck_path, out_path):
    ck = torch.load(ck_path)
    vocab = ck["vocab"]
    model = QMoth(len(vocab)); model.load_state_dict(ck["model"]); model.eval()
    ex = model.export()
    c = ex["cfg"]
    src = ["/* Generated by model/export_c.py: do not edit. */\n#include \"weights.h\"\n\n",
           "/* The brain: screen rows 0..BRAIN_ROWS-1 hold model data (visible as pixels). */\n"]
    for row in range(BRAIN_ROWS):
        if row == XROW:
            continue                           # activation page (row.s), not data
        page = 0x08 + row
        src.append(f"#pragma glcc segment({hex(page << 8)}, {hex((page << 8) + 160)}, \"D\")\n")
    hdr = ["/* Generated by model/export_c.py: do not edit. */\n#ifndef WEIGHTS_H\n#define WEIGHTS_H\n",
           f"#define V {len(vocab)}\n#define D {c['d']}\n#define NL {c['L']}\n#define NH {c['h']}\n",
           f"#define DH {c['d'] // c['h']}\n#define MLP {c['m']}\n#define CTX {CTX}\n",
           f"#define LEMB {ex['lemb']}\n#define TOK_Q {vocab.index('<q>')}\n#define TOK_A {vocab.index('<a>')}\n",
           f"#define TOK_E {vocab.index('<e>')}\n#define TOK_UNK {vocab.index('<unk>')}\n",
           f"#define BRAIN_ROWS {BRAIN_ROWS}\n#define NEXP {len(EXP)}\n#define NRCP {len(RCP)}\n"]
    total = 0

    def matrix(name, W):
        nonlocal total
        chs = chunks_of(rows_of(W))
        for j, ch in enumerate(chs):
            src.append(carr(f"{name}_{j}", ch)); total += len(ch)
        src.append(f"unsigned char *{name}[{len(chs)}] = {{{','.join(f'{name}_{j}' for j in range(len(chs)))}}};\n")
        hdr.append(f"extern unsigned char *{name}[];\n")
        total += 2 * len(chs)

    matrix("m_emb", ex["emb"])
    shifts = []
    for l, b in enumerate(ex["blocks"]):
        d = c["d"]
        for k, W in [("q", b["qkv"][:d]), ("k", b["qkv"][d:2 * d]), ("v", b["qkv"][2 * d:]),
                     ("o", b["o"]), ("up", b["up"]), ("down", b["down"])]:
            matrix(f"m_{k}{l}", W)
        shifts.append([b[k] for k in ["lq", "lk", "lv", "latt", "lo", "lup", "ldown"]])
    for k in ["q", "k", "v", "o", "up", "down"]:
        src.append(f"unsigned char **m_{k}x[NL] = {{{','.join(f'm_{k}{l}' for l in range(c['L']))}}};\n")
        hdr.append(f"extern unsigned char **m_{k}x[];\n")
    for i, name in enumerate(["LQ", "LK", "LV", "LATT", "LO", "LUP", "LDOWN"]):
        src.append(carr(f"sh_{name.lower()}", [s[i] for s in shifts], "signed char"))
        hdr.append(f"extern signed char sh_{name.lower()}[];\n")

    # position embeddings: ternary rows, +-2^LPOS
    matrix("m_pos", ex["pos"])
    hdr.append(f"#define LPOS {ex['lpos']}\n")

    # KV cache: one 32-byte array for k and one for v, per layer and position
    for kind in "kv":
        for l in range(c["L"]):
            for t in range(CTX):
                src.append(f"signed char {kind}c_{l}_{t}[D];\n")
            src.append(f"signed char *{kind}c_{l}[CTX] = {{{','.join(f'{kind}c_{l}_{t}' for t in range(CTX))}}};\n")
        src.append(f"signed char **{kind}c[NL] = {{{','.join(f'{kind}c_{l}' for l in range(c['L']))}}};\n")
        hdr.append(f"extern signed char **{kind}c[];\n")

    # softmax tables (EXP <= 64, RCP <= 248: bytes)
    src.append(carr("exp_t", [int(x) for x in EXP]))
    rc = [int(x) for x in RCP]
    for j in range(0, len(rc), CHUNK):
        src.append(carr(f"rcp_{j // CHUNK}", rc[j:j + CHUNK]))
    src.append(f"unsigned char *rcp_t[{(len(rc) + CHUNK - 1) // CHUNK}] = {{{','.join(f'rcp_{j // CHUNK}' for j in range(0, len(rc), CHUNK))}}};\n")
    hdr.append("extern unsigned char exp_t[];\nextern unsigned char *rcp_t[];\n")
    sq = [n * n // 4 for n in range(128)]
    src.append(carr("sqlo", [x & 255 for x in sq]))
    src.append(carr("sqhi", [x >> 8 for x in sq]))
    hdr.append("extern unsigned char sqlo[], sqhi[];\n")
    hdr.append(f"#define RCP_CHUNK {CHUNK}\n")

    # vocabulary: words packed as "w\0w\0..." in chunks of <= CHUNK bytes (no pointer per word)
    words = [w.encode() + b"\0" for w in vocab]
    chunks, cur, first = [], b"", [0]
    for i, w in enumerate(words):
        if len(cur) + len(w) > CHUNK:
            chunks.append(cur); cur = b""; first.append(i)
        cur += w
    chunks.append(cur)
    for j, ch in enumerate(chunks):
        src.append(carr(f"words_{j}", list(ch), "char"))
    src.append(f"char *words_t[{len(chunks)}] = {{{','.join(f'words_{j}' for j in range(len(chunks)))}}};\n")
    src.append(carr("words_first", first + [len(vocab)]))
    hdr.append(f"extern char *words_t[];\nextern unsigned char words_first[];\n#define NWCHUNK {len(chunks)}\n#endif\n")

    open(out_path, "w").write("".join(src))
    open(out_path.replace(".c", ".h"), "w").write("".join(hdr))
    print(f"weights + pos: {total} bytes, KV cache: {c['L'] * CTX * 2 * c['d']} bytes")


if __name__ == "__main__":
    main(*sys.argv[1:])
